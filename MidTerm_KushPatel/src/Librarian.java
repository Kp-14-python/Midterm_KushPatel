
public class Librarian extends LibraryStaff implements Reservable, Reportable  {
	    protected final int dailyIssueLimit;
	    protected final int booksProcessed;

	    public Librarian(String personId, String name, String phoneNumber, String staffId, String department, double monthlySalary, int dailyIssueLimit, int booksProcessed) {
	        super(personId, name, phoneNumber, staffId, department, monthlySalary); //This is value from Person class(Parent class)
	        //This value I am taking in this class.
	        this.dailyIssueLimit = dailyIssueLimit;
	        this.booksProcessed = Math.max(0, booksProcessed);
	    }

	    public int getDailyIssueLimit() {
	    	return dailyIssueLimit; 
	    	}
	    public int getBooksProcessed() {
	    	return booksProcessed;
	    	}
//This Override method come from LibreryStaff class
	    @Override
	    public double calculateMonthlyCompensation() {
	        // Salary plus $2.00 per book processed
	        return monthlySalary + (booksProcessed * 2.00);
	    }

	    // Overloaded calculateLateFee methods
	    public double calculateLateFee(int daysOverdue) {
	        return calculateLateFee(daysOverdue, 1.00); // Default daily rate $1.00
	    }
        //This are the exceptions. 
	    public double calculateLateFee(int daysOverdue, double dailyRate) {
	        if (daysOverdue < 0) {
	            throw new IllegalArgumentException("Days overdue cannot be negative.");
	        }
	        if (dailyRate < 0) {
	            throw new IllegalArgumentException("Daily rate cannot be negative.");
	        }
	        return daysOverdue * dailyRate;
	    }
	  //This is the same function i use in Member class that's way i use override.
	    @Override
	    public String getRoleDescription() {
	        return "Librarian";
	    }
        //This Finction i uses in Reservable which is interface.
        //I use override methode
	    @Override
	    public boolean reserveBook(String bookId) {
	        if (bookId == null || bookId.trim().isEmpty()) {
	            System.out.println("Reservation failed: Invalid Book ID.");
	            return false;
	        }
	        System.out.println("Librarian " + name + " successfully reserved book ID: " + bookId);
	        return true;
	    }
	  //This Finction i uses in Reportable which is interface.
	  //I use override methode
	    @Override
	    public void generateReport() {
	        System.out.println("--- Library Activity Report (Generated by Librarian " + name + ") ---");
	        System.out.println("Department: " + department + " , Books Processed: " + booksProcessed);
	    }
//This function i use in LibraryStaff class. Hence, i use override method.
	    @Override
	    public void displayStaffDetails() {
	        super.displayStaffDetails();
	        System.out.println("Monthly compensation: $" + String.format("%.2f", calculateMonthlyCompensation()));
	        System.out.println("Role: " + getRoleDescription());
	        System.out.println("Daily issue limit: " + dailyIssueLimit);
	    }
	}

